    val width: Int,
    val height: Int,
    val fps: Float,
    val hasEmbeddedSubtitles: Boolean,
    val subtitleCodec: String = "",
    val videoCodec: String = "",
    val videoCodecMimeType: String = "",
  )

  /**
   * Rotation only needs the Android retriever; do not open native MediaInfo for it.
   */
  suspend fun getRotation(
    context: Context,
    uri: Uri,
    fileName: String = "",
  ): Int =
    withContext(Dispatchers.IO) {
      runCatching {
        context.contentResolver.openFileDescriptor(uri, "r")?.use { descriptor ->
          val retriever = MediaMetadataRetriever()
          try {
            retriever.setDataSource(descriptor.fileDescriptor)
            retriever.extractMetadata(MediaMetadataRetriever.METADATA_KEY_VIDEO_ROTATION)
              ?.toFloatOrNull()?.toInt() ?: 0
          } finally {
            retriever.release()
          }
        } ?: 0
      }.getOrDefault(0)
    }
